#!/usr/bin/env python3
"""Translate the approved Python rectangle/group generator into native scene data.
Never executes either generator's HTML-writing footer.
"""
from pathlib import Path
from types import SimpleNamespace
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent
base = {}
exec((ROOT / 'sketch_base.py').read_text().split('cards = [')[0], base)
drop = {'cs': SimpleNamespace(**base)}
source = (ROOT / 'sketch_drop.py').read_text()
exec(source[source.index('r, g, STYLE, battery ='):source.rindex('cards = [')], drop)
outfits = dict(drop)
outfits['INK'] = drop['B']['ink']
outfit_source = (ROOT / 'sketch_outfits.py').read_text()
exec(outfit_source[outfit_source.index('def outfit(name):'):outfit_source.index('def pet(name):')], outfits)

def number(value):
    return format(float(value) / 10, '.10g')

def node(element, indent):
    pad = ' ' * indent
    cls = element.attrib.get('class', '')
    if element.tag == 'rect':
        values = ','.join(f'{name}: {number(element.attrib[name])}' for name in ('x', 'y', 'width', 'height'))
        return f'{pad}.rect(CGRect({values}),"{element.attrib["fill"].lstrip("#")}","{cls}")'
    assert element.tag == 'g', element.tag
    return f'{pad}.group("{cls}",[\n' + ',\n'.join(node(c, indent+4) for c in element) + f'\n{pad}])'

cards = [('idle',''),('thinking',''),('working',''),('done',''),('error',''),('sleeping',''),
         ('working','test'),('idle','rain'),('done','splash')]
lines = ['// BEGIN GENERATED DROP GEOMETRY', '// Generated by generate_geometry.py from sketch_drop.py and sketch_base.py.', 'private enum DropGeometry {',
         '    static func scene(mood: PetState,signature: String) -> ([PixelNode],[PixelNode]) {', '        switch mood.rawValue + "|" + signature {']
for mood,act in cards:
    key = mood + (act.title() if act else '')
    lines.append(f'        case "{mood}|{act}": return ({key}Inner,{key}Props)')
lines += ['        default: return scene(mood: mood,signature: "")', '        }', '    }']
for mood,act in cards:
    key = mood + (act.title() if act else '')
    fragments = [('Inner', drop['drop'](mood)+drop['face'](mood,act or None)+drop['limbs'](mood,act or None)),
                 ('Props', drop['props'](mood,act or None))]
    for suffix,fragment in fragments:
        elements = ET.fromstring('<root>'+fragment+'</root>')
        lines += [f'    private static let {key}{suffix}: [PixelNode] = [', ',\n'.join(node(e,8) for e in elements), '    ]']
lines += ['}', 'private enum DropOutfitGeometry {',
          '    static func nodes(_ outfit: Outfit) -> [PixelNode] {', '        switch outfit {']
for name, _ in outfits['NAMES']:
    elements = ET.fromstring('<root>'+outfits['outfit'](name)+'</root>')
    lines += [f'        case .{name}: return [', ',\n'.join(node(e,12) for e in elements), '        ]']
lines += ['        }', '    }', '}', '// END GENERATED DROP GEOMETRY']
replacement = '\n'.join(lines)
path = ROOT / 'CodexPet.swift'
source = path.read_text()
start = source.index('// BEGIN GENERATED DROP GEOMETRY')
end = source.index('// END GENERATED DROP GEOMETRY') + len('// END GENERATED DROP GEOMETRY')
if '--check' in sys.argv:
    if source[start:end] != replacement:
        sys.exit('FAIL: native rectangle scene differs from approved generator; run ./generate_geometry.py')
    print('PASS: all nine scenes and eight outfits match the approved generators')
else:
    path.write_text(source[:start]+replacement+source[end:])
    print('Generated nine exact scenes and eight exact outfits')
